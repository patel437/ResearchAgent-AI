"""
Research report generation endpoint.

Workflow:
  1. IBM Granite generates a full Markdown research report.
  2. Report is saved to local disk (Markdown and optionally DOCX).
  3. File metadata is persisted in IBM Cloudant together with report content.
  4. Caller receives report content + saved_id for future downloads.

Download endpoints:
  GET /{report_id}/download?fmt=md    – Markdown file
  GET /{report_id}/download?fmt=docx  – Word document
  Both endpoints verify user ownership before serving the file.
"""
import io
import uuid as _uuid

from fastapi import APIRouter, HTTPException, Query
from fastapi.responses import FileResponse, StreamingResponse
from pydantic import BaseModel

from app.services.cloudant_service import cloudant_service
from app.services.granite_service import granite_service
from app.services.local_storage_service import local_storage

router = APIRouter()


# ── Request / response models ─────────────────────────────────────

class ReportRequest(BaseModel):
    topic: str
    papers: list[dict]
    additional_context: str = ""
    user_id: str = "demo-user"
    save: bool = True
    export_format: str = "md"   # "md" | "docx"


# ── Generate ──────────────────────────────────────────────────────

@router.post("/generate")
async def generate_report(req: ReportRequest):
    """
    Generate a structured research report with IBM Granite,
    save it locally, and persist metadata in IBM Cloudant.
    """
    if not req.topic:
        raise HTTPException(status_code=400, detail="Research topic is required")
    if not req.papers:
        raise HTTPException(status_code=400, detail="At least one paper is required")

    # 1. IBM Granite generation
    try:
        result = await granite_service.generate_report(
            req.topic, req.papers, req.additional_context
        )
    except Exception as exc:
        raise HTTPException(status_code=500, detail=f"Report generation error: {exc}")

    report_content = result["report"]

    # 2. Save to local disk
    file_meta = local_storage.save_report(
        report_content,
        req.topic,
        req.user_id,
        fmt=req.export_format if req.export_format in ("md", "docx") else "md",
    )

    # 3. Persist to Cloudant
    saved = None
    if req.save:
        try:
            saved = cloudant_service.save_report(
                req.user_id,
                req.topic,
                report_content,
                [
                    {
                        "title": p.get("title"),
                        "authors": p.get("authors"),
                        "doi": p.get("doi"),
                        "year": p.get("year"),
                    }
                    for p in req.papers[:15]
                ],
                file_metadata=file_meta,
            )
        except Exception:
            pass  # Non-fatal; file already saved locally

    return {
        "topic": req.topic,
        "report": report_content,
        "paper_count": len(req.papers),
        "saved_id": saved.get("_id") if saved else None,
        "file_id": file_meta["file_id"],
        "stored_name": file_meta["filename"],
        "format": file_meta["format"],
        "size_bytes": file_meta["size_bytes"],
        "storage": "local",
        "ai_generated": True,
        "disclaimer": (
            "Generated by ResearchAgent AI using IBM Granite. "
            "Verify all citations before academic submission."
        ),
    }


# ── List & retrieve ───────────────────────────────────────────────

@router.get("/list")
async def list_reports(user_id: str = Query(default="demo-user")):
    """List all saved reports for a user."""
    reports = cloudant_service.get_reports(user_id)
    # Attach storage stats per report
    for r in reports:
        fm = r.get("file_metadata", {})
        r["has_local_file"] = bool(
            fm.get("stored_name")
            and local_storage.get_report_path(user_id, fm["stored_name"])
        )
    return {"reports": reports, "total": len(reports)}


@router.get("/{report_id}")
async def get_report(report_id: str, user_id: str = Query(default="demo-user")):
    """Get a specific report record."""
    report = cloudant_service.get_report(report_id)
    if not report:
        raise HTTPException(status_code=404, detail="Report not found")
    if report.get("user_id") and report["user_id"] != user_id:
        raise HTTPException(status_code=403, detail="Access denied")
    return report


# ── Download ──────────────────────────────────────────────────────

@router.get("/{report_id}/download")
async def download_report(
    report_id: str,
    fmt: str = Query(default="md", description="md | docx"),
    user_id: str = Query(default="demo-user"),
):
    """
    Download a report as Markdown (.md) or Word (.docx).

    Priority:
      1. Serve the file from local disk if it exists.
      2. If the on-disk file is gone, regenerate from the Cloudant content.
    """
    report = cloudant_service.get_report(report_id)
    if not report:
        raise HTTPException(status_code=404, detail="Report not found")
    if report.get("user_id") and report["user_id"] != user_id:
        raise HTTPException(status_code=403, detail="Access denied")

    content = report.get("content", "# Report\n\nContent unavailable")
    topic = report.get("topic", "research")
    file_meta = report.get("file_metadata", {})
    stored_name = file_meta.get("stored_name", "")

    # Determine MIME type and extension
    if fmt == "docx":
        media_type = "application/vnd.openxmlformats-officedocument.wordprocessingml.document"
        ext = "docx"
    else:
        media_type = "text/markdown"
        ext = "md"

    safe_topic = topic.replace(" ", "_")[:40]
    download_filename = f"report_{safe_topic}.{ext}"

    # 1. Try to serve existing local file
    if stored_name:
        # If fmt matches, serve directly
        stored_ext = stored_name.rsplit(".", 1)[-1].lower()
        if stored_ext == ext:
            path = local_storage.get_report_path(user_id, stored_name)
            if path:
                return FileResponse(
                    path=str(path),
                    media_type=media_type,
                    filename=download_filename,
                )

    # 2. Generate on-the-fly from stored content
    if fmt == "docx":
        from app.services.local_storage_service import _markdown_to_docx
        data = _markdown_to_docx(content)
        return StreamingResponse(
            io.BytesIO(data),
            media_type=media_type,
            headers={"Content-Disposition": f'attachment; filename="{download_filename}"'},
        )
    else:
        return StreamingResponse(
            io.BytesIO(content.encode("utf-8")),
            media_type=media_type,
            headers={"Content-Disposition": f'attachment; filename="{download_filename}"'},
        )


# ── Delete ────────────────────────────────────────────────────────

@router.delete("/{report_id}")
async def delete_report(
    report_id: str,
    rev: str = Query(default=""),
    user_id: str = Query(default="demo-user"),
):
    """Delete a report (local file + Cloudant record)."""
    report = cloudant_service.get_report(report_id)
    if not report:
        raise HTTPException(status_code=404, detail="Report not found")
    if report.get("user_id") and report["user_id"] != user_id:
        raise HTTPException(status_code=403, detail="Access denied")

    # Delete local file
    fm = report.get("file_metadata", {})
    stored_name = fm.get("stored_name", "")
    disk_deleted = local_storage.delete_report_file(user_id, stored_name) if stored_name else False

    # Delete Cloudant record
    cloudant_deleted = False
    if rev:
        try:
            from app.services.cloudant_service import cloudant_service as _cs
            cloudant_deleted = _cs._delete_document(
                _cs._get_client() and __import__("app.core.config", fromlist=["settings"]).settings.CLOUDANT_DB_REPORTS,
                report_id,
                rev,
            )
        except Exception:
            pass

    return {"success": True, "disk_deleted": disk_deleted, "cloudant_deleted": cloudant_deleted}
